// Liste blanche : une valeur inattendue dans localStorage ne doit pas casser les traductions
let currentLang = 'fr';
try { if (localStorage.getItem('lang') === 'en') currentLang = 'en'; } catch (e) { /* stockage indisponible */ }

function applyLang(lang) {
  const dict = i18n[lang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });
  document.getElementById('lang-label').textContent = lang === 'fr' ? 'EN' : 'FR';
  document.documentElement.lang = lang;
  document.querySelectorAll('.count[data-val]').forEach(el => {
    const dec = +el.dataset.dec;
    el.textContent = (+el.dataset.val).toLocaleString(lang === 'en' ? 'en-US' : 'fr-FR', { minimumFractionDigits: dec, maximumFractionDigits: dec });
  });
}

function toggleLang() {
  currentLang = currentLang === 'fr' ? 'en' : 'fr';
  try { localStorage.setItem('lang', currentLang); } catch (e) { /* stockage indisponible */ }
  applyLang(currentLang);
}

applyLang(currentLang);

document.getElementById('lang-toggle').addEventListener('click', toggleLang);
document.getElementById('theme-toggle').addEventListener('click', toggleTheme);

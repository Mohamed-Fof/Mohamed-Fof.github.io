/* ===== THEME TOGGLE ===== */
// init.js a déjà posé le thème sur l'accueil ; ailleurs on le lit ici (choix enregistré, sinon celui du système)
(function() {
  let saved = document.documentElement.getAttribute('data-theme');
  if (saved !== 'dark' && saved !== 'light') {
    try { saved = localStorage.getItem('theme'); } catch (e) { saved = null; }
    if (saved !== 'dark' && saved !== 'light') saved = window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
  }
  document.documentElement.setAttribute('data-theme', saved);
  updateThemeIcon(saved);
})();

function updateThemeIcon(theme) {
  const sun = document.getElementById('icon-sun');
  const moon = document.getElementById('icon-moon');
  if (!sun || !moon) return;
  if (theme === 'dark') {
    sun.style.display = 'block';
    moon.style.display = 'none';
  } else {
    sun.style.display = 'none';
    moon.style.display = 'block';
  }
}

function toggleTheme() {
  const current = document.documentElement.getAttribute('data-theme') || 'light';
  const next = current === 'dark' ? 'light' : 'dark';
  document.documentElement.setAttribute('data-theme', next);
  try { localStorage.setItem('theme', next); } catch (e) { /* stockage indisponible */ }
  updateThemeIcon(next);
}

